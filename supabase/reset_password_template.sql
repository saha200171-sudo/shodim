-- «Сходим?» — шаблон: поставить новый пароль, если кто-то забыл старый.
--
-- Как пользоваться:
--   1. Скопируйте весь текст ниже (Ctrl+A, Ctrl+C).
--   2. Supabase → SQL Editor → New query → вставьте.
--   3. Замените ДВЕ вещи в кавычках:
--        'новый-пароль'        → новый пароль (минимум 6 символов)
--        'pochta@example.com'  → почта аккаунта, которому меняем пароль
--   4. Нажмите Run.
--
-- Что должно получиться:
--   внизу появится строка с этой почтой и надписью «пароль обновлён» — всё готово,
--   можно входить в приложение с новым паролем.
--   Если внизу пусто («No rows returned») — почта написана с ошибкой, проверьте её.
--
-- Важно: вписывайте пароль только в SQL Editor, не сохраняйте его в этом файле.
-- Места, визиты и фото при смене пароля не меняются.

update auth.users
set encrypted_password = extensions.crypt('новый-пароль', extensions.gen_salt('bf')),
    updated_at = now()
where email = lower(trim('pochta@example.com'))
returning email, 'пароль обновлён' as result;
